let currentLocale: Locale = 'ja'

export function setLocale(locale: Locale) {
  currentLocale = locale
  if (typeof window !== 'undefined') {
    localStorage.setItem('doccraft:locale', locale)
  }
}

export function getLocale(): Locale {
  if (typeof window !== 'undefined') {
    const saved = localStorage.getItem('doccraft:locale') as Locale | null
    if (saved && translations[saved]) {
      currentLocale = saved
    }
  }
  return currentLocale
}

export function t(key: string): string {
  return translations[currentLocale]?.[key] || translations.ja[key] || key
}

export function getAvailableLocales(): { code: Locale; label: string }[] {
  return [
    { code: 'ja', label: '日本語' },
    { code: 'en', label: 'English' },
  ]
}
